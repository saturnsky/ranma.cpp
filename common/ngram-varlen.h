#pragma once

#include "llama.h"

#include <cstdint>
#include <unordered_map>
#include <vector>

//
// common_ngram_varlen
//
// ranma: a variable-length n-gram drafter over the tokens of the session ("autocomplete of the model's own output").
//
// The history is kept as segments: each run of new text in a prompt and the tokens each request generated. Prompt
// text that an earlier request of the session already held (a shared prefix, or a run of at least n_dedup tokens
// equal to an earlier request) is not counted again; generated tokens always are. Every 3-gram of a segment is a
// sample. A lookup takes the samples whose 3 tokens equal the last 3 of the context and extends each match backwards
// to its length n. For each n, longest first, the samples that match at least n tokens form a cohort, and the draft
// follows the continuation of the weighted majority as long as
//   - its weight is at least p_min of the weight of the whole cohort (samples that end early stay in the total),
//   - at least n_support samples agree on every token so far, and
//   - the draft is at most ladder*(support - 1) tokens long.
// The first cohort that drafts at least one token wins. A sample weighs 2^(-age/half_life) (age: tokens added since),
// times w_prompt for prompt text; samples older than window tokens expire at the end of a request.
//
// The definition follows the CPU replay that chose these settings (variant b): the same input gives the same draft.
// Nothing is stored on disk.

struct common_ngram_varlen_params {
    int32_t n_min       = 3;       // shortest matched context
    int32_t n_support   = 2;       // samples that agree on every drafted token
    double  p_min       = 0.9;     // weight share of the cohort that agrees on every drafted token
    int32_t ladder      = 4;       // a draft of k tokens needs k <= ladder*(support - 1)
    double  half_life   = 16384.0; // tokens
    double  w_prompt    = 0.25;    // weight of prompt text relative to generated tokens
    int64_t window      = 131072;  // tokens; older samples expire
    int32_t n_dedup     = 16;      // a prompt run of at least this many tokens seen before is not new text
    int64_t n_prior_max = 524288;  // tokens of earlier requests kept for the new-text test
};

struct common_ngram_varlen_draft {
    std::vector<llama_token> tokens; // the draft, empty when no cohort qualifies
    int32_t n         = 0;           // matched context length of the cohort
    int32_t n_samples = 0;           // samples in the cohort
};

class common_ngram_varlen {
public:
    common_ngram_varlen(const common_ngram_varlen_params & params, uint32_t n_seq);

    // a new request on the sequence with its whole prompt; ends the previous request of the sequence if needed
    void begin(llama_seq_id seq_id, const std::vector<llama_token> & prompt);

    // a token generated by the current request of the sequence
    void add(llama_seq_id seq_id, llama_token token);

    // the end of the current request: its text becomes an earlier request, old samples expire
    void end(llama_seq_id seq_id);

    // the draft that continues prompt + generated tokens of the current request
    common_ngram_varlen_draft draft(llama_seq_id seq_id) const;

    bool   active     (llama_seq_id seq_id) const;
    size_t n_prompt   (llama_seq_id seq_id) const;
    size_t n_generated(llama_seq_id seq_id) const;

    // prompt + generated tokens of the current request
    const std::vector<llama_token> & history(llama_seq_id seq_id) const;

    int64_t get_clock()     const { return clock; }
    size_t  get_n_samples() const;

private:
    struct key3 {
        llama_token t0;
        llama_token t1;
        llama_token t2;

        bool operator==(const key3 & o) const { return t0 == o.t0 && t1 == o.t1 && t2 == o.t2; }
    };

    struct key3_hash {
        size_t operator()(const key3 & k) const;
    };

    struct entry {
        int32_t sid; // segment
        int32_t p;   // position of the last token of the 3-gram in the segment
    };

    struct segment {
        std::vector<llama_token> tokens;
        bool    prompt;
        int64_t base; // clock of the token at position 0
        bool    live; // the generated tokens of a request still running
    };

    struct seq_state {
        bool    active   = false;
        size_t  n_prompt = 0;
        int32_t sid      = -1; // the segment of the generated tokens
        std::vector<llama_token> history;
    };

    common_ngram_varlen_params params;

    int64_t clock = 0;

    std::vector<segment> segments;
    std::unordered_map<key3, std::vector<entry>, key3_hash> index;

    // earlier requests (prompt + generated), for the new-text test
    std::vector<std::vector<llama_token>> prior;
    size_t  prior_first   = 0; // the oldest request still kept
    int64_t prior_tokens  = 0;
    int64_t prior_dropped = 0; // tokens dropped since seen16 was built
    std::unordered_map<uint64_t, std::vector<uint64_t>> seen16; // hash of n_dedup tokens -> (request << 32 | pos)

    std::vector<seq_state> seqs;

    uint64_t hash_run(const llama_token * tokens) const;
    void     add_prior(const std::vector<llama_token> & tokens);
    void     rebuild_seen();
    std::vector<uint8_t> new_mask(const std::vector<llama_token> & prompt) const;
    void     purge();
};
